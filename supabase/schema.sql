-- Group preference survey (anonymous to students)
create table if not exists public.ratings (
  rater_id   uuid not null references public.profiles(id) on delete cascade,
  ratee_id   uuid not null references public.profiles(id) on delete cascade,
  score      smallint not null check (score between 1 and 5),
  updated_at timestamptz not null default now(),
  primary key (rater_id, ratee_id),
  check (rater_id <> ratee_id)
);
create table if not exists public.survey_submissions (
  user_id      uuid primary key references public.profiles(id) on delete cascade,
  days         text[] default '{}',
  note         text,
  submitted_at timestamptz not null default now()
);

-- Sessions + impact
create table if not exists public.sessions (
  id          bigint generated always as identity primary key,
  group_id    int references public.groups(id) on delete cascade,
  date        date not null,
  start_time  text,
  end_time    text,
  location    text,
  supervisor  text,
  notes       text,
  status      text not null default 'scheduled' check (status in ('scheduled','done','cancelled')),
  bags        int  check (bags >= 0),
  kg          numeric(7,1) check (kg >= 0),
  photos_url  text,
  created_at  timestamptz not null default now()
);

create table if not exists public.attendance (
  session_id bigint not null references public.sessions(id) on delete cascade,
  user_id    uuid   not null references public.profiles(id) on delete cascade,
  status     text   not null check (status in ('present','absent','excused','late')),
  primary key (session_id, user_id)
);

-- "I can't make it" requests (24h notice rule)
create table if not exists public.absence_requests (
  id         bigint generated always as identity primary key,
  session_id bigint not null references public.sessions(id) on delete cascade,
  user_id    uuid   not null references public.profiles(id) on delete cascade,
  reason     text   not null,
  status     text   not null default 'pending' check (status in ('pending','approved','declined')),
  created_at timestamptz not null default now(),
  unique (session_id, user_id)
);

