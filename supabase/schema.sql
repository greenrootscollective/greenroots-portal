create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  sid int := nullif(new.raw_user_meta_data->>'school_id','')::int;
  dom text := lower(split_part(new.email, '@', 2));
  sch schools;
begin
  select * into sch from schools where id = sid and active;
  if sch.id is null then
    raise exception 'Please choose your school.';
  end if;
  if dom <> lower(sch.student_domain) and dom <> lower(coalesce(sch.staff_domain, '')) then
    raise exception 'Please use your school email address for %.', sch.name;
  end if;
  insert into profiles (id, email, full_name, class, school_id)
  values (new.id, lower(new.email),
          coalesce(nullif(trim(new.raw_user_meta_data->>'full_name'),''), split_part(new.email,'@',1)),
          new.raw_user_meta_data->>'class', sch.id);
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- Not security definer on purpose: current_user tells us whether the change
-- comes from the website (role "authenticated") or a trusted function / SQL editor.
create or replace function public.profiles_guard()
returns trigger language plpgsql set search_path = public as $$
begin
  if tg_op = 'UPDATE' and current_user in ('authenticated','anon') and not public.is_admin() then
    new.role := old.role; new.status := old.status; new.group_id := old.group_id;
    new.grc_id := old.grc_id; new.grc_id_manual := old.grc_id_manual;
    new.email := old.email; new.school_id := old.school_id;
  end if;
  if not new.grc_id_manual then new.grc_id := public.make_grc_id(new.full_name, new.phone); end if;
  return new;
end $$;

drop trigger if exists profiles_guard on public.profiles;
create trigger profiles_guard before insert or update on public.profiles
  for each row execute function public.profiles_guard();

-- Approving an absence request marks the student "excused"
create or replace function public.absence_to_attendance()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.status = 'approved' then
    insert into attendance (session_id, user_id, status) values (new.session_id, new.user_id, 'excused')
    on conflict (session_id, user_id) do update set status = 'excused';
  end if;
  return new;
end $$;
drop trigger if exists absence_to_attendance on public.absence_requests;
create trigger absence_to_attendance after update of status on public.absence_requests
  for each row execute function public.absence_to_attendance();

