create or replace function public.redeem_code(code text)
returns text language plpgsql security definer set search_path = public as $$
declare s app_secrets;
begin
  if auth.uid() is null then raise exception 'Not signed in'; end if;
  select * into s from app_secrets where id = 1;
  if upper(trim(code)) = upper(s.admin_code) then
    update profiles set role = 'admin', status = 'member' where id = auth.uid(); return 'admin';
  elsif upper(trim(code)) = upper(s.join_code) then
    update profiles set status = 'member' where id = auth.uid() and status <> 'inactive'; return 'member';
  end if;
  raise exception 'That code is not valid. Check with the GRC team.';
end $$;

-- Safe directory (no emails / phones)
create or replace view public.member_directory as
  select p.id, p.full_name, p.class, p.school_id,
         case when public.groups_published() or public.is_admin() then p.group_id end as group_id
  from profiles p
  where p.status = 'member' and p.role = 'student' and public.is_member();
grant select on public.member_directory to authenticated;

create or replace function public.save_survey(p_ratings jsonb, p_days text[], p_note text)
returns void language plpgsql security definer set search_path = public as $$
declare r record;
begin
  if not public.is_member() then raise exception 'Join the initiative first.'; end if;
  if not (select survey_open from app_settings where id = 1) then raise exception 'The survey is closed.'; end if;
  delete from ratings where rater_id = auth.uid();
  for r in select key::uuid as ratee, value::int as score from jsonb_each_text(p_ratings) loop
    -- only other active student members can be rated (never admins, never yourself)
    if r.ratee <> auth.uid() and r.score between 1 and 5
       and exists (select 1 from profiles where id = r.ratee and role = 'student' and status = 'member') then
      insert into ratings (rater_id, ratee_id, score) values (auth.uid(), r.ratee, r.score);
    end if;
  end loop;
  insert into survey_submissions (user_id, days, note, submitted_at)
  values (auth.uid(), coalesce(p_days,'{}'), p_note, now())
  on conflict (user_id) do update set days = excluded.days, note = excluded.note, submitted_at = now();
end $$;

create or replace function public.save_groups(p_count int, p_assign jsonb)
returns void language plpgsql security definer set search_path = public as $$
declare i int; r record;
begin
  if not public.is_admin() then raise exception 'Admins only'; end if;
  for i in 1..p_count loop
    insert into groups (id, name) values (i, 'Group ' || i) on conflict (id) do nothing;
  end loop;
  update profiles set group_id = null where role = 'student' and group_id is not null;
  for r in select key::uuid as uid, value::int as gid from jsonb_each_text(p_assign) loop
    update profiles set group_id = r.gid where id = r.uid;
  end loop;
  delete from groups where id > p_count;
  update app_settings set num_groups = p_count where id = 1;
end $$;

create or replace function public.reset_survey()
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'Admins only'; end if;
  delete from ratings where true;
  delete from survey_submissions where true;
end $$;

-- Public numbers for the landing page (no personal data)
create or replace function public.public_stats()
returns json language sql stable security definer set search_path = public as $$
  select json_build_object(
    'members',  (select count(*) from profiles where status = 'member' and role = 'student'),
    'sessions', (select count(*) from sessions where status = 'done'),
    'kg',       (select coalesce(sum(kg),0) from sessions where status = 'done'),
    'bags',     (select coalesce(sum(bags),0) from sessions where status = 'done'),
    'schools',  (select count(*) from schools where active)
  );
$$;

-- Friendly group league (members only)
create or replace function public.group_league()
returns table (group_id int, sessions bigint, kg numeric, bags bigint, attendance_rate numeric)
language sql stable security definer set search_path = public as $$
  select s.group_id,
         count(*) filter (where s.status = 'done'),
         coalesce(sum(s.kg) filter (where s.status = 'done'), 0),
         coalesce(sum(s.bags) filter (where s.status = 'done'), 0),
         (select round(100.0 * count(*) filter (where a.status in ('present','late')) / nullif(count(*),0))
            from attendance a join sessions s2 on s2.id = a.session_id where s2.group_id = s.group_id)
  from sessions s
  where (public.is_member() and public.groups_published()) or public.is_admin()
  group by s.group_id order by s.group_id;
$$;

