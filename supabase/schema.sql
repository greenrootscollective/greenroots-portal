create table if not exists public.groups (
  id         int primary key,
  name       text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.profiles (
  id            uuid primary key references auth.users(id) on delete cascade,
  email         text not null,
  full_name     text not null,
  school_id     int references public.schools(id),
  class         text,
  phone_cc      text,
  phone         text,
  grc_id        text,
  grc_id_manual boolean not null default false,
  role          text not null default 'student' check (role in ('student','admin')),
  status        text not null default 'pending' check (status in ('pending','member','inactive')),
  group_id      int references public.groups(id) on delete set null,
  created_at    timestamptz not null default now()
);

create table if not exists public.app_settings (
  id               int primary key default 1 check (id = 1),
  survey_open      boolean not null default true,
  groups_published boolean not null default false,
  num_groups       int not null default 4
);
