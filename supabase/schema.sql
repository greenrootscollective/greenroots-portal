-- schools: anyone (even signed out) can see active schools for the sign-up form
create policy "schools read"  on public.schools for select using (active or public.is_admin());
create policy "schools write" on public.schools for all using (public.is_admin()) with check (public.is_admin());

create policy "profiles read"   on public.profiles for select using (id = auth.uid() or public.is_admin());
create policy "profiles update" on public.profiles for update using (id = auth.uid() or public.is_admin());
create policy "profiles delete" on public.profiles for delete using (public.is_admin());

create policy "groups read"  on public.groups for select using (public.is_admin() or (public.is_member() and public.groups_published()));
create policy "groups write" on public.groups for all using (public.is_admin()) with check (public.is_admin());

create policy "settings read"  on public.app_settings for select using (auth.uid() is not null);
create policy "settings write" on public.app_settings for update using (public.is_admin());
create policy "secrets admin"  on public.app_secrets for all using (public.is_admin()) with check (public.is_admin());

-- ratings: a student only ever sees their own answers; admins see all
create policy "ratings read"   on public.ratings for select using (rater_id = auth.uid() or public.is_admin());
create policy "ratings delete" on public.ratings for delete using (public.is_admin());
create policy "survey read"    on public.survey_submissions for select using (user_id = auth.uid() or public.is_admin());
create policy "survey delete"  on public.survey_submissions for delete using (public.is_admin());

create policy "sessions read"  on public.sessions for select using (
  public.is_admin()
  or (public.is_member() and group_id = public.my_group() and public.groups_published())
  or exists (select 1 from attendance a where a.session_id = sessions.id and a.user_id = auth.uid()));
create policy "sessions write" on public.sessions for all using (public.is_admin()) with check (public.is_admin());

create policy "attendance read"  on public.attendance for select using (user_id = auth.uid() or public.is_admin());
create policy "attendance write" on public.attendance for all using (public.is_admin()) with check (public.is_admin());

create policy "absence read"   on public.absence_requests for select using (user_id = auth.uid() or public.is_admin());
create policy "absence insert" on public.absence_requests for insert with check (
  user_id = auth.uid() and public.is_member() and status = 'pending'
  and exists (select 1 from sessions s where s.id = session_id and s.group_id = public.my_group()));
create policy "absence own delete" on public.absence_requests for delete using (
  (user_id = auth.uid() and status = 'pending') or public.is_admin());
create policy "absence admin update" on public.absence_requests for update using (public.is_admin());

create policy "tasks read"  on public.tasks for select using ((active and public.is_member()) or public.is_admin());
create policy "tasks write" on public.tasks for all using (public.is_admin()) with check (public.is_admin());

create policy "task_done read"   on public.task_done for select using (user_id = auth.uid() or public.is_admin());
create policy "task_done insert" on public.task_done for insert with check (user_id = auth.uid() and public.is_member());
create policy "task_done delete" on public.task_done for delete using (user_id = auth.uid() or public.is_admin());

create policy "reflections read"   on public.reflections for select using (user_id = auth.uid() or public.is_admin());
create policy "reflections insert" on public.reflections for insert with check (
  user_id = auth.uid() and exists (select 1 from attendance a where a.session_id = reflections.session_id
                                   and a.user_id = auth.uid() and a.status in ('present','late')));
create policy "reflections update" on public.reflections for update using (user_id = auth.uid()) with check (
  user_id = auth.uid() and exists (select 1 from attendance a where a.session_id = reflections.session_id
                                   and a.user_id = auth.uid() and a.status in ('present','late')));

create policy "ann read"  on public.announcements for select using (public.is_member() or public.is_admin());
create policy "ann write" on public.announcements for all using (public.is_admin()) with check (public.is_admin());

